// Builds a small, self-hosted icon font containing ONLY the icons the site uses.
//
// Runs automatically before `npm run dev` and `npm run build` (see package.json), including on Vercel.
// It scans the source and data files for Font Awesome (`fa-…`) and Devicon (`devicon-…`) class names,
// then writes:
//   styles/icons.css        the CSS for those icons (imported by app/layout.js)
//   public/icons/*.woff2    subset fonts with only those glyphs
// So adding an icon to a data file (e.g. a skill in data/skills.js) needs no extra step: the next build
// includes it. Both outputs are committed too, so the site still works if this script is not run.

import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { join, extname } from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const subsetFont = require('subset-font');

const ROOT = process.cwd();
const SCAN_DIRS = ['app', 'components', 'sections', 'data', 'utils'];
const OUT_CSS = join(ROOT, 'styles', 'icons.css');
const OUT_FONTS = join(ROOT, 'public', 'icons');
const FA_DIR = join(ROOT, 'node_modules', '@fortawesome', 'fontawesome-free');
const DEVICON_DIR = join(ROOT, 'node_modules', 'devicon');

// ---------- 1. Collect class names used in the source ----------
function walk(dir, files = []) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path, files);
    else if (['.js', '.jsx', '.ts', '.tsx'].includes(extname(name))) files.push(path);
  }
  return files;
}

const source = SCAN_DIRS.flatMap((dir) => walk(join(ROOT, dir))).map((file) => readFileSync(file, 'utf8')).join('\n');
const faNames = new Set([...source.matchAll(/\bfa-([a-z0-9]+(?:-[a-z0-9]+)*)/g)].map((m) => m[1]));
const deviconNames = new Set([...source.matchAll(/\bdevicon-([a-z0-9]+(?:-[a-z0-9]+)*)/g)].map((m) => m[1]));

// ---------- 2. Font Awesome ----------
const faCss = readFileSync(join(FA_DIR, 'css', 'fontawesome.css'), 'utf8');
const firstIconRule = faCss.search(/^\.fa-0::before/m);
// Everything before the first icon rule: base classes, sizes and animations (license header kept)
const faBase = faCss.slice(0, firstIconRule);

// Map every icon class to its codepoint, e.g. ".fa-robot::before { content: "\f544"; }".
// all.css holds the solid/regular icons (::before) AND the brand icons (:before); aliases share a rule.
const faAllCss = readFileSync(join(FA_DIR, 'css', 'all.css'), 'utf8');
const faCodepoints = new Map();
for (const match of faAllCss.matchAll(/((?:\.fa-[a-z0-9-]+::?before,?\s*)+)\{\s*content:\s*"\\([0-9a-f]+)"/g)) {
  for (const sel of match[1].matchAll(/\.fa-([a-z0-9-]+)::?before/g)) faCodepoints.set(sel[1], parseInt(match[2], 16));
}

const usedFa = [...faNames].filter((name) => faCodepoints.has(name)).sort();
const faChars = usedFa.map((name) => String.fromCodePoint(faCodepoints.get(name))).join('');

// ---------- 3. Devicon ----------
const devCss = readFileSync(join(DEVICON_DIR, 'devicon.min.css'), 'utf8');
const devCodepoints = new Map();
for (const match of devCss.matchAll(/((?:\.devicon-[a-z0-9-]+:before,?)+)\{content:"([^"]+)"\}/g)) {
  for (const sel of match[1].matchAll(/\.devicon-([a-z0-9-]+):before/g)) devCodepoints.set(sel[1], match[2]);
}
const usedDevicon = [...deviconNames].filter((name) => devCodepoints.has(name)).sort();
const devChars = usedDevicon.map((name) => devCodepoints.get(name)).join('');

const unknownDevicon = [...deviconNames].filter((name) => !devCodepoints.has(name));
if (unknownDevicon.length) console.warn(`[icons] Devicon classes not found in devicon 2.16.0: ${unknownDevicon.join(', ')}`);

// ---------- 4. Subset fonts ----------
mkdirSync(OUT_FONTS, { recursive: true });
async function subset(input, chars, output) {
  const font = readFileSync(input);
  const result = await subsetFont(font, chars || ' ', { targetFormat: 'woff2' });
  writeFileSync(join(OUT_FONTS, output), result);
  return result.length;
}

const sizes = {
  'fa-solid-900.woff2': await subset(join(FA_DIR, 'webfonts', 'fa-solid-900.ttf'), faChars, 'fa-solid-900.woff2'),
  'fa-regular-400.woff2': await subset(join(FA_DIR, 'webfonts', 'fa-regular-400.ttf'), faChars, 'fa-regular-400.woff2'),
  'fa-brands-400.woff2': await subset(join(FA_DIR, 'webfonts', 'fa-brands-400.ttf'), faChars, 'fa-brands-400.woff2'),
  'devicon.woff2': await subset(join(DEVICON_DIR, 'fonts', 'devicon.ttf'), devChars, 'devicon.woff2')
};

// ---------- 5. CSS ----------
const fontFace = (family, weight, file) =>
  `@font-face {\n  font-family: '${family}';\n  font-style: normal;\n  font-weight: ${weight};\n  font-display: block;\n  src: url('/icons/${file}') format('woff2');\n}\n`;

const css = `/* GENERATED by scripts/build-icons.mjs. Do not edit by hand: it is rewritten on every build. */
/* Font Awesome Free 6.4.0 (https://fontawesome.com/license/free: icons CC BY 4.0, fonts SIL OFL 1.1, code MIT) */
/* Devicon 2.16.0 (MIT). Only the ${usedFa.length} Font Awesome and ${usedDevicon.length} Devicon icons used on the site are included. */

:root {
  --fa-style-family-classic: 'Font Awesome 6 Free';
  --fa-font-solid: normal 900 1em/1 'Font Awesome 6 Free';
  --fa-font-regular: normal 400 1em/1 'Font Awesome 6 Free';
  --fa-style-family-brands: 'Font Awesome 6 Brands';
  --fa-font-brands: normal 400 1em/1 'Font Awesome 6 Brands';
}

${fontFace('Font Awesome 6 Free', 900, 'fa-solid-900.woff2')}
${fontFace('Font Awesome 6 Free', 400, 'fa-regular-400.woff2')}
${fontFace('Font Awesome 6 Brands', 400, 'fa-brands-400.woff2')}
.fas,
.fa-solid {
  font-weight: 900;
}

.far,
.fa-regular {
  font-weight: 400;
}

.fab,
.fa-brands {
  font-weight: 400;
}

${faBase.replace(/^\/\*![\s\S]*?\*\/\s*/, '')}
${usedFa.map((name) => `.fa-${name}::before {\n  content: "\\${faCodepoints.get(name).toString(16)}";\n}`).join('\n\n')}

/* ---- Devicon ---- */
@font-face {
  font-family: 'devicon';
  font-style: normal;
  font-weight: normal;
  font-display: block;
  src: url('/icons/devicon.woff2') format('woff2');
}

[class^='devicon-'],
[class*=' devicon-'] {
  font-family: 'devicon' !important;
  speak: never;
  font-style: normal;
  font-weight: normal;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${usedDevicon.map((name) => `.devicon-${name}:before {\n  content: "\\${devCodepoints.get(name).codePointAt(0).toString(16)}";\n}`).join('\n\n')}
`;

writeFileSync(OUT_CSS, css);

const total = Object.values(sizes).reduce((a, b) => a + b, 0);
console.log(
  `[icons] ${usedFa.length} Font Awesome + ${usedDevicon.length} Devicon icons -> styles/icons.css (${Math.round(css.length / 1024)} KB) + fonts ${Math.round(total / 1024)} KB`
);
